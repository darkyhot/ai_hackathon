"""«Спросить агента»: свободные вопросы клиента в любой момент диалога.

Клиент пишет или говорит вопрос («что такое безопасные расчёты?», «почему справедливая цена такая?»,
«сколько я переплачу?») — агент отвечает с учётом своей сессии.

- Системный промпт — единый промпт агента из docs/AGENT_PROMPT.md (раздел 1): документ команды
  и есть поведение агента в коде.
- Числа модель не считает: берёт из контекста сессии, который собирает код.
- Без LLM (офлайн/демо) отвечают правила по частым темам — с теми же числами сессии.
"""
from __future__ import annotations

import json
import logging
import re
from functools import lru_cache

from ..config import ROOT
from ..llm import LLMError
from . import mortgage as M
from .tools import fmt

log = logging.getLogger(__name__)

QUESTION = re.compile(
    r"\?\s*$|^\s*(?:а\s+)?(?:что|как|почему|зачем|сколько|когда|где|какой|какая|какое|какие|кто|чем|чего|"
    r"можно ли|нужно ли|надо ли|правда ли|объясни|расскажи|подскажи)\b",
    re.I,
)

FALLBACK_PROMPT = ("Ты — ИИ-агент покупателя квартиры на платформе Домклик (Сбер). Отвечай честно, коротко, "
                   "по-русски, на «вы». Числа бери только из контекста.")

ANSWER_RULES = """
# Сейчас
Клиент задал вопрос посреди работы. Ответь на него в 2–5 предложениях, затем одной фразой верни
к текущему шагу. Числа бери ТОЛЬКО из контекста сессии ниже, не пересчитывай и не придумывай.
Если ответа нет ни в контексте, ни в правилах — честно скажи и предложи, как узнать.
Отвечай обычным текстом, без markdown-заголовков.

# Контекст сессии (посчитано кодом)
{context}"""


def is_question(text: str) -> bool:
    return bool(QUESTION.search(text.strip()))


@lru_cache(maxsize=1)
def agent_prompt() -> str:
    """Раздел 1 из docs/AGENT_PROMPT.md — блок ```text ... ```."""
    try:
        doc = (ROOT / "docs" / "AGENT_PROMPT.md").read_text(encoding="utf-8")
    except OSError:
        return FALLBACK_PROMPT
    m = re.search(r"```text\n(.*?)```", doc, re.S)
    return m.group(1).strip() if m else FALLBACK_PROMPT


def build_context(s) -> dict:
    """Короткая выжимка сессии: запрос, финансы, ипотека, подборка, текущий объект и звонок."""
    p = s.profile or {}
    ctx: dict = {"шаг": getattr(s, "stage", None)}
    if p.get("city"):
        ctx["запрос"] = p.get("summary") or {k: p.get(k) for k in ("city", "rooms", "budget_max")}
        ctx["способ оплаты"] = {"cash": "наличные", "mortgage_ready": "ипотека, взнос есть",
                                "mortgage_saving": "ипотека, взнос копит"}.get(p.get("payment"), "не выяснен")
    if s.mortgage:
        chosen = next(c for c in s.mortgage["programs"] if c["key"] == s.mortgage["chosen"])
        ctx["ипотека"] = {
            "считаем по": chosen["title"], "ставка": f"{chosen['rate'] * 100:.1f}%".replace(".", ","),
            "кредит": fmt(chosen["loan"]), "взнос": fmt(chosen["down_payment"]),
            "платёж": fmt(chosen["monthly"]), "переплата за весь срок": fmt(chosen["overpay"]), "срок": f"{chosen['years']} лет",
            "объяснение программ": s.mortgage["explanation"],
        }
        if s.mortgage.get("matcap"):
            ctx["ипотека"]["маткапитал во взнос"] = fmt(s.mortgage["matcap"]["amount"])
    if s.finance:
        f = s.finance
        ctx["финансы"] = {"нужно на взнос и сделку": fmt(f["need"]), "доступно сейчас": fmt(f["available"]),
                          "не хватает": fmt(f["gap"]), "откладывать в месяц": fmt(f["monthly"]),
                          "срок накопления, мес": f["months"], "вывод": f["verdict"]}
    if getattr(s, "shown", None):
        ctx["подборка"] = [
            {"адрес": x.get("address"), "цена": fmt(x["price"]), "справедливая": fmt(x["fair"]["fair"]),
             "коридор": f"{fmt(x['fair']['low'])}–{fmt(x['fair']['high'])}", "площадь": x.get("area"),
             "этаж": f"{x.get('floor')}/{x.get('floors')}", "основа оценки": x["fair"]["basis"]}
            for x in s.shown[:6]
        ]
    if getattr(s, "current", None):
        x, fp = s.current["listing"], s.current["fair"]
        ctx["текущий объект"] = {"адрес": x.get("address"), "цена в объявлении": fmt(x["price"]),
                                 "справедливая цена": fmt(fp["fair"]), "коридор": f"{fmt(fp['low'])}–{fmt(fp['high'])}",
                                 "переоценка": f"{fp['overprice_pct']}%", "основа оценки": fp["basis"],
                                 "цель торга": fmt(fp["target"])}
    if s.journal.get("final_price"):
        ctx["итог торга"] = {"цена объявления": fmt(s.journal["base_price"]), "договорились": fmt(s.journal["final_price"]),
                             "экономия": fmt(s.journal.get("savings", 0))}
    if s.notes:
        ctx["заметки клиента"] = s.notes[-5:]
    return ctx


# ---------------------------------------------------------------- ответы без LLM

def _mortgage_answer(ctx: dict) -> str | None:
    m = ctx.get("ипотека")
    if not m:
        return None
    return (f"Считаю по программе «{m['считаем по']}»: ставка {m['ставка']}, кредит {m['кредит']} на {m['срок']}, "
            f"платёж {m['платёж']} в месяц, переплата за весь срок — {m['переплата за весь срок']}. "
            "Каждые 100 000 ₽, которые я сторгую, уменьшают платёж.")


def rules_answer(text: str, ctx: dict) -> str:
    q = text.lower().replace("ё", "е")
    cur = ctx.get("текущий объект")
    first = (ctx.get("подборка") or [None])[0]
    if re.search(r"безопасн\w* расч|сбр\b|аккредитив", q):
        return ("Сервис безопасных расчётов Домклик: деньги покупателя (свои и кредитные) лежат на специальном счёте "
                "и уходят продавцу только после регистрации права собственности в Росреестре. Если сделка сорвётся — "
                "деньги вернутся вам. Это безопаснее наличных и банковской ячейки.")
    if re.search(r"справедлив|почему.*(цен|дорож|дешев)|откуда.*цен|оценк", q):
        x = cur or first
        if x:
            fair = x.get("справедливая цена") or x.get("справедливая")
            return (f"Справедливую цену считаю по похожим квартирам рядом: медиана цены квадратного метра, поправки на ремонт, "
                    f"год дома и этаж, минус ~3% — так обычно проходят сделки после торга. Для «{x['адрес']}» это {fair} "
                    f"(коридор {x['коридор']}); основа — {x['основа оценки']}. В продукте вместо медианы будет модель оценки "
                    "Домклик и цены реальных сделок.")
        return ("Справедливую цену считаю по похожим квартирам рядом: медиана цены квадратного метра, поправки на ремонт, "
                "год дома и этаж, минус ~3% на торг. Покажу на конкретной квартире, как только соберу подборку.")
    if re.search(r"маткапитал|материнск", q):
        return (f"Маткапитал в 2026 году — {fmt(M.MATCAP_FIRST)} на первого ребёнка и {fmt(M.MATCAP_SECOND)} на второго, "
                "если на первого не получали. Его можно направить в первоначальный взнос или в погашение долга по ипотеке. "
                "После покупки нужно выделить доли детям — это обязательство перед Соцфондом.")
    if re.search(r"семейн", q):
        m = ctx.get("ипотека")
        if m:
            return m["объяснение программ"]
        return ("Семейная ипотека с 01.10.2026 — для семей с ребёнком младше 7 лет: ставка от 10% при одном ребёнке "
                "до 2% при пяти (в Москве и Петербурге на 2 п.п. выше), лимит кредита от 6 до 18 млн ₽. "
                "На вторичку — только в городах, где почти не строят. Скажите, сколько у вас детей и возраст младшего — посчитаю.")
    if re.search(r"переплат|платеж|ставк|ипотек|кредит", q):
        return _mortgage_answer(ctx) or ("Ипотеку посчитаю на шаге «Финансы»: рыночная ставка Сбера на готовое жильё — от 15,5%, "
                                         "при взносе меньше 30% — около 17,5%. Семейная — от 10%, если есть ребёнок младше 7 лет.")
    if re.search(r"сколько.*(стоит|плат).*(агент|услуг|вы)|плат\w* агент|комисс|15\s*%|бесплатн", q):
        return ("Вы платите только за результат: 15% от экономии, которую я сторгую относительно цены объявления. "
                "Цена объявления фиксируется в журнале в момент старта. Нет экономии — нет платы.")
    if re.search(r"накоп|взнос|вклад|копить|облигац|акци", q):
        f = ctx.get("финансы")
        if f:
            return f"{f['вывод']} Нужно на взнос и сделку {f['нужно на взнос и сделку']}, откладывать — {f['откладывать в месяц']} в месяц."
        return ("Посчитаю план накопления на шаге «Финансы»: по доходам, расходам и накоплениям, с подушкой безопасности "
                "в 3 месяца расходов. Предложу три стратегии — от вкладов до облигаций; доходность — допущение, не обещание.")
    if re.search(r"риск|провер|мошен|обремен|егрн|юрид", q):
        return ("Сейчас проверяю риски по данным объявления: проверка Росреестром, апартаменты, торги, слова «доля», «наследство», "
                "«перепланировка». Перед сделкой закажем выписку ЕГРН и проверим продавца по ФССП и реестру банкротств. "
                "Нетиповые случаи — к юристу Домклик.")
    if re.search(r"звон|продав|торг", q):
        return ("Я звоню продавцу как ИИ-ассистент покупателя и сразу это говорю. Уточняю то, чего нет в объявлении, "
                "торгуюсь только аргументами (справедливая цена, срок продажи, дефекты) и никогда не предлагаю больше вашего лимита. "
                "Итоговую цену подтверждаете вы.")
    return ("Хороший вопрос — без подключённой модели я отвечаю только на частые темы: ипотека и семейная ипотека, маткапитал, "
            "справедливая цена, безопасные расчёты, накопления, проверка рисков, звонок продавцу, плата агенту. "
            "Записал вопрос — вернусь к нему, когда будет нужно.")


# ---------------------------------------------------------------- ответ

async def answer(s, text: str) -> str:
    ctx = build_context(s)
    system = agent_prompt() + "\n" + ANSWER_RULES.format(context=json.dumps(ctx, ensure_ascii=False, indent=1))
    try:
        resp = await s.llm.chat([{"role": "system", "content": system}, {"role": "user", "content": text}],
                                temperature=0.3, max_tokens=500, tag="answer")
        reply = resp.text.strip()
        if not reply:
            raise LLMError("пустой ответ")
    except LLMError as exc:
        log.info("answer fallback: %s", exc)
        reply = rules_answer(text, ctx)
    await s.say(reply)
    return reply
