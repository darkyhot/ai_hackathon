# Особые формы названий: сокращения и города, у которых основа меняется при склонении («в Орле»)
CITY_ALIASES = [
    (r"\bмск\b|москв", "Москва"),
    (r"петербург|питер|\bспб\b", "Санкт-Петербург"),
    (r"\bекб\b", "Екатеринбург"),
    (r"нижн\w* новгород", "Нижний Новгород"),
    (r"велик\w* новгород", "Великий Новгород"),
    (r"ростов\w*-на-дону|\bростов\w*\b", "Ростов-на-Дону"),
    (r"набережн\w* челн", "Набережные Челны"),
]


def city_stem(name: str) -> str:
    """Основа названия для поиска в тексте и в заголовке страницы: «Калуга» -> «калуг» (в Калуге, по Калуге)."""
    n = name.lower().replace("ё", "е")
    n = n.split("-на-")[0]
    return n[:-1] if len(n) > 3 and n[-1] in "аеиоуыьйяю" else n


# окончания падежей: «Калуг|а, -и, -е, -у, -ой» — только целое слово, чтобы «Чита» не находилась в «читаю»
CASE_ENDINGS = r"(?:|а|е|и|у|ы|ь|й|ю|я|ой|ей|ом|ем|ью|ах|ях|ам|ям|ами|ями|ов|ев)"


def normalize_city(text: str | None) -> str | None:
    if not text:
        return None
    t = text.lower().replace("ё", "е")
    for pattern, name in CITY_ALIASES:
        if re.search(pattern, t):
            return name
    for name in sorted(CIAN_REGIONS, key=len, reverse=True):
        stem = re.escape(city_stem(name))
        if re.search(r"(?<![а-я])" + stem + CASE_ENDINGS + r"(?![а-я])", t):
            return name
    return None


